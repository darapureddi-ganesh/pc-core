/** The policy schedule / declarations page. */
export function renderPolicySchedule(d: ScheduleData): string {
  const coverages = d.coverages
    .map((c) => `<tr><th>${esc(c.name)}</th><td>${esc(c.detail)}</td></tr>`)
    .join("");
  const premium = d.premium.lines
    .map(
      (l) =>
        `<tr><td>${esc(l.label)}</td><td class="money">${inr(l.amount)}</td></tr>`,
    )
    .join("");

  return page(
    "Policy Schedule",
    `<h1>Private Car Policy — Schedule</h1>
<table>
  <tr><th>Policy number</th><td>${esc(d.policyNumber)}</td></tr>
  <tr><th>Insured</th><td>${esc(d.insuredName)}</td></tr>
  <tr><th>Product</th><td>${esc(d.product)} (v${esc(d.productVersion)})</td></tr>
  <tr><th>Period of insurance</th><td>${esc(d.period.from)} to ${esc(d.period.to)}</td></tr>
  <tr><th>Registration no.</th><td>${esc(d.vehicle.registrationNo)}</td></tr>
  <tr><th>Vehicle</th><td>${esc(d.vehicle.description)} · ${esc(d.vehicle.cc)} cc · RTO zone ${esc(d.vehicle.rtoZone)}</td></tr>
  <tr><th>Insured declared value (IDV)</th><td>${inr(d.vehicle.idv)}</td></tr>
  <tr><th>No-claim bonus</th><td>${esc(d.ncb)}%</td></tr>
</table>
<h1>Coverages</h1>
<table>${coverages}</table>
<h1>Premium</h1>
<table>${premium}<tr class="total"><td>Total premium payable</td><td class="money">${inr(d.premium.total)}</td></tr></table>`,
  );
}

