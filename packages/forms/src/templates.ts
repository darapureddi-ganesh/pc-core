const CSV_COLUMNS: Array<keyof RegisterRow> = [
  "policyNumber",
  "product",
  "inception",
  "expiry",
  "sumInsured",
  "odPremium",
  "tpPremium",
  "gst",
  "total",
];

/** IRDAI-style premium register: one row per issued policy, CSV. */
export function renderPremiumRegisterCsv(rows: RegisterRow[]): string {
  const header = CSV_COLUMNS.join(",");
  const body = rows.map((r) => CSV_COLUMNS.map((c) => r[c]).join(",")).join("\n");
  return rows.length ? `${header}\n${body}` : header;
}
